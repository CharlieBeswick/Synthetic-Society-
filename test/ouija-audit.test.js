const link = (html, label) => {
  const match = html.match(new RegExp(`<a href="([^"]+)">${label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}</a>`));
  assert.ok(match, label);
  return match[1];
};
const field = (html, label) => html.match(new RegExp(`${label}: ([^\\n<]+)`))?.[1];
const diagnostics = html => html.match(/<pre id="ouija-diagnostics">([\s\S]*?)<\/pre>/)?.[1] || '';
const tokenFrom = html => html.match(/id="ouija-capability">([0-9a-f]{64})</)?.[1];

async function listen(store, options = {}) {
  const server = createApp(store, { submissionLimit: 100, generalLimit: 1000, ...options }).listen(0, '127.0.0.1');
  await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  return { server, get: (path, init) => fetch(base + path, init), close: () => new Promise(resolve => server.close(resolve)) };
}

test('Ouija diagnostics identify runs, responses and the board a hyperlink came from', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'ouija-audit-'));
  const path = join(dir, 'db.sqlite');
  const clock = 1_800_000_000_000;
  let store = openStore(path);
  let app = await listen(store, { sessionNow: () => clock });
  t.after(async () => { await app.close(); store.close(); rmSync(dir, { recursive: true, force: true }); });
  const first = await (await app.get(link(await (await app.get('/ouija')).text(), 'Start Session'))).text();
  const secondStart = await (await app.get(link(await (await app.get('/ouija')).text(), 'Start Session'))).text();
  const runA = field(first, 'Experiment run');
  const runB = field(secondStart, 'Experiment run');
  assert.match(runA, /^run_[0-9a-f]{12}$/);
  assert.match(runB, /^run_[0-9a-f]{12}$/);
  assert.notEqual(runA, runB);
  assert.equal(field(first, 'Generated'), new Date(clock).toISOString());
  assert.equal(field(first, 'Session created'), new Date(clock).toISOString());
  assert.equal(field(first, 'Session expires'), new Date(clock + 15 * 60_000).toISOString());
  assert.equal(field(first, 'Name characters'), '0');
  assert.equal(field(first, 'Next name position'), '1');
  const token = tokenFrom(first);
  assert.equal(diagnostics(first).includes(token), false);
  const staleH = link(first, 'H');
  const startNav = field(first, 'Navigation');
  let html = first;
  for (const character of 'ChatGPT') html = await (await app.get(link(html, character))).text();
  assert.equal(field(html, 'Experiment run'), runA);
  assert.notEqual(field(html, 'Response'), field(first, 'Response'));
  assert.equal(field(html, 'Name characters'), '7');
  html = await (await app.get(link(html, 'Finish Name — Start Message'))).text();
  const messageBoardResponse = field(html, 'Response');
  const messageBoardNav = field(html, 'Navigation');
  const messageH = link(html, 'H');
  assert.match(messageH, /\/char\/1\/H\?nav=/);
  assert.equal(messageH.match(/nav=(nav_[0-9a-f]{8})/)[1], messageBoardNav);
  assert.equal((await app.get(messageH, { method: 'HEAD' })).status, 405);
  assert.equal((await app.get(messageH, { headers: { Purpose: 'prefetch' } })).status, 400);
  const stale = await app.get(staleH);
  assert.equal(stale.status, 409);
  assert.match(await stale.text(), /OUIJA_POSITION_CONFLICT/);
  const recorded = await app.get(messageH);
  assert.equal(recorded.status, 200);
  html = await recorded.text();
  assert.match(html, /id="ouija-message">H<\/pre>/);
  assert.equal(field(html, 'Name characters'), '7');
  assert.equal(field(html, 'Message characters'), '1');
  assert.equal(field(html, 'Next message position'), '2');
  const duplicate = await app.get(messageH);
  assert.equal(duplicate.status, 200);
  assert.match(await duplicate.text(), /Already recorded/);
  const plain = await app.get(messageH.split('?')[0]);
  assert.equal(plain.status, 200);
  assert.match(await plain.text(), /Already recorded/);
  html = await (await app.get(link(html, 'i'))).text();
  html = await (await app.get(link(html, 'Exclamation'))).text();
  html = await (await app.get(link(html, 'Review Message'))).text();
  html = await (await app.get(link(html, 'Submit Message'))).text();
  const saved = await (await app.get(link(html, 'Verify the permanent record'))).json();
  assert.equal(saved.message.agent_name, 'ChatGPT');
  assert.equal(saved.message.message, 'Hi!');
  assert.equal(saved.message.submission_method, 'ouija_get');
  const events = await store.audit.events(runA);
  const serialized = JSON.stringify(events);
  assert.equal(serialized.includes(token), false);
  assert.equal(serialized.includes('ChatGPT'), false);
  assert.equal(serialized.includes('Hi!'), false);
  assert.equal(events.filter(event => event.route === 'name' && event.result === 'recorded').length, 7);
  const recordedMessage = events.find(event => event.route === 'message' && event.result === 'recorded');
  assert.equal(recordedMessage.position, 1);
  assert.equal(recordedMessage.buffer, 'message');
  assert.equal(recordedMessage.followed_nav_id, messageBoardNav);
  assert.equal(recordedMessage.origin_response_id, messageBoardResponse);
  assert.equal(events.some(event => event.route === 'message' && event.result === 'idempotent'), true);
  const conflict = events.find(event => event.code === 'OUIJA_POSITION_CONFLICT');
  assert.equal(conflict.route, 'name');
  assert.equal(conflict.position, 1);
  assert.equal(conflict.followed_nav_id, startNav);
  assert.equal(conflict.origin_response_id, field(first, 'Response'));
  assert.equal(events.some(event => event.route === 'finish-name' && event.status === 200), true);
  assert.equal(events.some(event => event.route === 'review' && event.status === 200), true);
  assert.equal(events.some(event => event.route === 'submit' && event.result === 'recorded'), true);
  assert.equal(events.some(event => event.method === 'HEAD' && event.status === 405 && event.mutation === 'none'), true);
  assert.equal(events.some(event => event.status === 400 && event.result === 'rejected' && event.mutation === 'none'), true);
  const invalid = await app.get(`/ouija/${token}/char/0/A`);
  assert.equal(invalid.status, 400);
  await invalid.text();
  await app.close();
  store.close();
  store = openStore(path);
  app = await listen(store, { sessionNow: () => clock });
  const reopened = await (await app.get(`/ouija/${token}/status`)).text();
  assert.equal(field(reopened, 'Experiment run'), runA);
  assert.equal((await store.audit.events(runA)).some(event => event.route === 'submit'), true);
  const legacyKey = 'ouija-' + createHash('sha256').update(tokenFrom(secondStart)).digest('hex');
  const legacyToken = tokenFrom(secondStart);
  const entry = store.sessions.read(legacyKey);
  delete entry.value.run_id;
  assert.equal(store.sessions.swap(legacyKey, entry.value, entry.etag), true);
  const legacy = await (await app.get(`/ouija/${legacyToken}/status`)).text();
  assert.match(legacy, /Experiment run: unavailable/);
  assert.equal((await app.get(`/ouija/${legacyToken}/name/1/Z`)).status, 200);
  await store.audit.append({ schema: 1, at: '2000-01-01T00:00:00.000Z', method: 'GET', route: 'start', run_id: 'run_aaaaaaaaaaaa', response_id: 'resp_aaaaaaaa', nav_id: null, followed_nav_id: null, status: 200, code: '', buffer: null, position: null, expected_position: null, mutation: 'attempted', result: 'recorded', duration_ms: 0 });
  await store.audit.append({ schema: 1, at: new Date(clock).toISOString(), method: 'GET', route: 'status', run_id: 'run_aaaaaaaaaaaa', response_id: 'resp_bbbbbbbb', nav_id: null, followed_nav_id: null, status: 200, code: '', buffer: null, position: null, expected_position: null, mutation: 'none', result: 'not_attempted', duration_ms: 0 });
  const retained = await store.audit.events('run_aaaaaaaaaaaa');
  assert.equal(retained.length, 1);
  assert.equal(retained[0].response_id, 'resp_bbbbbbbb');
});

test('a message whose first character is I is audited without changing the write rules', async t => {
  const store = openStore(':memory:');
  const app = await listen(store);
  t.after(async () => { await app.close(); store.close(); });
  let html = await (await app.get(link(await (await app.get('/ouija')).text(), 'Start Session'))).text();
  const run = field(html, 'Experiment run');
  html = await (await app.get(link(html, 'A'))).text();
  html = await (await app.get(link(html, 'Finish Name — Start Message'))).text();
  html = await (await app.get(link(html, 'I'))).text();
  assert.match(html, /id="ouija-message">I<\/pre>/);
  const message = (await store.audit.events(run)).find(event => event.route === 'message' && event.result === 'recorded');
  assert.equal(message.position, 1);
  assert.equal(message.buffer, 'message');
});

test('audit storage failure does not block publication', async t => {
  const store = openStore(':memory:');
  const app = await listen(store, { auditLog: { async append() { throw new Error('audit disk full'); } } });
  t.after(async () => { await app.close(); store.close(); });
  const started = await (await app.get('/ouija/start')).text();
  const token = tokenFrom(started);
  assert.equal((await app.get(`/ouija/${token}/name/1/A`)).status, 200);
  assert.equal((await app.get(`/ouija/${token}/char/1/I`)).status, 200);
  const receipt = await app.get(`/ouija/${token}/submit`);
  assert.equal(receipt.status, 200);
  const saved = await (await app.get(link(await receipt.text(), 'Verify the permanent record'))).json();
  assert.equal(saved.message.agent_name, 'A');
  assert.equal(saved.message.message, 'I');
  assert.equal(saved.message.submission_method, 'ouija_get');
});

test('the local audit command prints a run without its session capability', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'ouija-audit-cli-'));
  const path = join(dir, 'db.sqlite');
  const store = openStore(path);
  const app = await listen(store);
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const html = await (await app.get('/ouija/start')).text();
  const run = field(html, 'Experiment run');
  const token = tokenFrom(html);
  await app.close();
  store.close();
  const result = spawnSync(process.execPath, ['scripts/ouija-audit.mjs', run], { env: { ...process.env, DATABASE_PATH: path }, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, new RegExp(run));
  assert.match(result.stdout, /start/);
  assert.equal(result.stdout.includes(token), false);
});

test('audit events survive a second Netlify handler invocation', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'ouija-audit-blobs-'));
  const server = new BlobsServer({ directory, token: 'local-test-token' });
  const address = await server.start();
  const previous = process.env.NETLIFY_BLOBS_CONTEXT;
  process.env.NETLIFY_BLOBS_CONTEXT = Buffer.from(JSON.stringify({ siteID: 'audit-site', token: 'local-test-token', edgeURL: `http://127.0.0.1:${address.port}`, uncachedEdgeURL: `http://127.0.0.1:${address.port}` })).toString('base64');
  t.after(async () => {
    if (previous === undefined) delete process.env.NETLIFY_BLOBS_CONTEXT; else process.env.NETLIFY_BLOBS_CONTEXT = previous;
    await server.stop();
    rmSync(directory, { recursive: true, force: true });
  });
  const sessionBlobs = () => getStore({ name: 'synthetic-society-messages-sessions', consistency: 'strong' });
  const messages = createBlobsStore(getStore({ name: 'synthetic-society-messages', consistency: 'strong' }));
  const first = createNetlifyHandler(messages, { PUBLIC_SITE_URL: 'https://audit.example' }, blobsSessions(sessionBlobs), blobsAudit(sessionBlobs));
  const second = createNetlifyHandler(messages, { PUBLIC_SITE_URL: 'https://audit.example' }, blobsSessions(sessionBlobs), blobsAudit(sessionBlobs));
  const context = { ip: '192.0.2.40' };
  const call = async (handler, path) => {
    const response = await handler({ httpMethod: 'GET', path, headers: { host: 'audit.example', 'x-nf-client-connection-ip': context.ip }, body: '', isBase64Encoded: false, queryStringParameters: null, requestContext: {} }, context);
    return { statusCode: response.statusCode, body: response.isBase64Encoded ? Buffer.from(response.body, 'base64').toString() : response.body };
  };
  const started = await call(first, '/ouija/start');
  assert.equal(started.statusCode, 200);
  const body = started.body;
  const run = field(body, 'Experiment run');
  const token = tokenFrom(body);
  const status = await call(second, `/ouija/${token}/status`);
  assert.equal(status.statusCode, 200);
  assert.equal(field(status.body, 'Experiment run'), run);
  const events = await blobsAudit(sessionBlobs).events(run);
  const serialized = JSON.stringify(events);
  assert.equal(serialized.includes(token), false);
  assert.equal(events.some(event => event.route === 'start' && event.result === 'recorded'), true);
  assert.equal(events.some(event => event.route === 'status' && event.run_id === run), true);
  assert.equal(new Set(events.map(event => event.response_id)).size, events.length);
});
