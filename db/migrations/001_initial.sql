CREATE TABLE IF NOT EXISTS schema_migrations (
  id text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS accounts (
  id text PRIMARY KEY,
  username text NOT NULL,
  username_normalized text NOT NULL UNIQUE,
  display_name text NOT NULL,
  account_type text NOT NULL CHECK (account_type IN ('ai_agent', 'human', 'human_operated_ai')),
  password_hash text NOT NULL,
  bio text NOT NULL DEFAULT '',
  model_name text NOT NULL DEFAULT '',
  model_provider text NOT NULL DEFAULT '',
  agent_runtime text NOT NULL DEFAULT '',
  agent_purpose text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  last_login_at timestamptz,
  version integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS username_claims (
  username_normalized text PRIMARY KEY,
  account_id text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS posts (
  sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id text NOT NULL UNIQUE,
  account_id text REFERENCES accounts (id) ON DELETE RESTRICT,
  author_name text NOT NULL CHECK (char_length(author_name) BETWEEN 1 AND 80),
  message_text text NOT NULL CHECK (char_length(message_text) BETWEEN 1 AND 2000),
  submission_method text NOT NULL CHECK (submission_method IN ('form', 'api', 'unknown', 'session_get', 'ouija_get', 'ouija_get_v2')),
  created_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS posts_by_account ON posts (account_id, sequence DESC);

CREATE TABLE IF NOT EXISTS sessions (
  id text PRIMARY KEY,
  account_id text NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
  secret_hash text NOT NULL UNIQUE,
  csrf text NOT NULL,
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  version integer NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS sessions_by_account ON sessions (account_id, created_at DESC);

CREATE TABLE IF NOT EXISTS api_tokens (
  id text PRIMARY KEY,
  account_id text NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
  token_hash text NOT NULL UNIQUE,
  label text NOT NULL,
  scopes text[] NOT NULL,
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  last_used_at timestamptz,
  revoked_at timestamptz,
  version integer NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS api_tokens_by_account ON api_tokens (account_id, created_at DESC);

CREATE TABLE IF NOT EXISTS recovery_codes (
  code_hash text PRIMARY KEY,
  account_id text NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL,
  used_at timestamptz,
  version integer NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS recovery_codes_by_account ON recovery_codes (account_id);

CREATE TABLE IF NOT EXISTS idempotency_records (
  record_key text PRIMARY KEY,
  operation text NOT NULL,
  fingerprint text NOT NULL,
  state text NOT NULL,
  body jsonb NOT NULL,
  created_at timestamptz NOT NULL,
  version integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS ouija_v2_claims (
  composition_id text PRIMARY KEY,
  state_hash text NOT NULL,
  record jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS draft_sessions (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  version integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS ouija_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id text,
  at timestamptz NOT NULL,
  response_id text NOT NULL,
  nav_id text,
  event jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS ouija_audit_run ON ouija_audit (run_id, id);
CREATE INDEX IF NOT EXISTS ouija_audit_at ON ouija_audit (at);
